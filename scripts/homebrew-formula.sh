#!/usr/bin/env bash
# Print a Homebrew formula for a published release of the verity CLI.
#
#   scripts/homebrew-formula.sh <version> <SHA256SUMS> <download-base-url>
#
# <download-base-url> is where the release archives live, e.g.
# https://example.com/owner/verity/releases/download/v0.2.0. The formula
# installs the macOS or Linux archive for the machine's CPU and checks it
# against the given SHA256SUMS. The release workflow writes it to
# Formula/verity.rb in the tap repository; see docs/releasing.md.
set -euo pipefail

version=${1:?usage: scripts/homebrew-formula.sh <version> <SHA256SUMS> <download-base-url>}
sums=${2:?usage: scripts/homebrew-formula.sh <version> <SHA256SUMS> <download-base-url>}
base=${3:?usage: scripts/homebrew-formula.sh <version> <SHA256SUMS> <download-base-url>}
base=${base%/}

sum() {
  local f="verity_${version}_$1.tar.gz" s
  s=$(awk -v f="$f" '$2 == f || $2 == "*"f { print $1 }' "$sums")
  [ -n "$s" ] || { echo "no checksum for $f in $sums" >&2; exit 1; }
  printf '%s' "$s"
}

cat <<EOF
# Generated by scripts/homebrew-formula.sh for ${version}. Do not edit.
class Verity < Formula
  desc "API contract testing for REST, SOAP and GraphQL (verity CLI)"
  homepage "${HOMEPAGE:-${base%/releases/download/*}}"
  version "${version#v}"
  license "MIT"

  on_macos do
    on_arm do
      url "${base}/verity_${version}_darwin_arm64.tar.gz"
      sha256 "$(sum darwin_arm64)"
    end
    on_intel do
      url "${base}/verity_${version}_darwin_amd64.tar.gz"
      sha256 "$(sum darwin_amd64)"
    end
  end

  on_linux do
    on_arm do
      url "${base}/verity_${version}_linux_arm64.tar.gz"
      sha256 "$(sum linux_arm64)"
    end
    on_intel do
      url "${base}/verity_${version}_linux_amd64.tar.gz"
      sha256 "$(sum linux_amd64)"
    end
  end

  def install
    bin.install "verity"
  end

  test do
    assert_match "${version}", shell_output("#{bin}/verity version")
  end
end
EOF
